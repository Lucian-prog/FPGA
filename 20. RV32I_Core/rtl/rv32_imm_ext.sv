// =============================================================================
// rv32_imm_ext —— 立即数扩展器（I / S / B / J 四种格式）
// -----------------------------------------------------------------------------
// 教学要点：
//   RISC-V 把立即数“打碎”嵌在指令编码里，不同指令格式的拼接方式不同。
//   这个模块的工作就是按 imm_src_i 指定的格式，把散落的位段重新拼成
//   一个 32 位有符号立即数，并做符号扩展（用最高位 instr[31] 填充高位）。
//
//   四种格式对照（ imm 位编号从低到高）：
//     I 型（addi/lw）：imm[11:0]  = instr[31:20]
//                      → 直接符号扩展到 32 位。
//     S 型（sw）：     imm[11:5]  = instr[31:25]，imm[4:0] = instr[11:7]
//                      → 立即数被拆成两段，为 rs2 字段让位。
//     B 型（beq）：    imm[12|10:5|4:1] = instr[31|30:25|11:8]，imm[0]=0
//                      → 位序打乱，最低位恒 0（跳转目标至少 2 字节对齐）。
//     J 型（jal）：    imm[20|10:1|11|19:12] = instr[31|30:21|20|19:12]，imm[0]=0
//                      → 同样位序打乱，低位补 0。
//
//   为什么 B/J 型位序这么“扭曲”？因为 RISC-V 刻意让立即数的各个位
//   尽量落在指令编码的固定位置上（比如 imm 最高位永远在 instr[31]），
//   这样硬件只需简单布线就能拼接，不需要复杂的移位网络——
//   这是“编码设计迁就硬件实现”的经典案例。
//
//   本模块没有任何寄存器，综合出来就是一团导线（加少量符号扩展逻辑）。
// =============================================================================
module rv32_imm_ext (
  input  logic [31:0] instr_i,    // 整条 32 位指令（只用其中的立即数位段）
  input  logic [1:0]  imm_src_i,  // 立即数格式选择，来自主译码器
  output logic [31:0] imm_ext_o   // 符号扩展后的 32 位立即数
);

  localparam logic [1:0] IMM_I = 2'b00;
  localparam logic [1:0] IMM_S = 2'b01;
  localparam logic [1:0] IMM_B = 2'b10;
  localparam logic [1:0] IMM_J = 2'b11;

  // 立即数生成器本质上是布线和位拼接，不包含寄存器。
  // B/J 型偏移量天然按 2 字节对齐，因此最低位由硬件补 0。
  // 注意所有格式都用 instr_i[31] 做符号位——这正是 RISC-V 编码的
  // 设计意图：符号位位置固定，符号扩展只需一种电路。
  always_comb begin
    case (imm_src_i)
      IMM_I: imm_ext_o = {{20{instr_i[31]}}, instr_i[31:20]};
      IMM_S: imm_ext_o = {{20{instr_i[31]}}, instr_i[31:25],
                          instr_i[11:7]};
      IMM_B: imm_ext_o = {{20{instr_i[31]}}, instr_i[7],
                          instr_i[30:25], instr_i[11:8], 1'b0};
      IMM_J: imm_ext_o = {{12{instr_i[31]}}, instr_i[19:12],
                          instr_i[20], instr_i[30:21], 1'b0};
      default: imm_ext_o = 32'h0000_0000;
    endcase
  end

endmodule
