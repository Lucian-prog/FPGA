// =============================================================================
// rv32_adder —— 32 位加法器
// -----------------------------------------------------------------------------
// 教学要点：
//   数据通路里有两个独立的加法器，各自承担不同的 PC 计算任务：
//     1. PC + 4   —— 顺序执行时的下一条指令地址（RISC-V 指令定长 4 字节）；
//     2. PC + imm —— beq / jal 的跳转目标地址（B 型 / J 型立即数）。
//
//   为什么不复用 ALU 来算 PC？因为 ALU 在同一周期正忙着执行指令本身的
//   运算（比如 beq 要做减法比较）。单周期处理器的特点是“一条指令一个
//   周期内做完所有事”，所以每一类并行的运算都需要独立的硬件——
//   这正是“用面积换时间”的典型例子。
//
//   综合结果：一个 32 位进位传播加法器（行为级写法，综合器自选实现）。
// =============================================================================
module rv32_adder (
  input  logic [31:0] a_i,
  input  logic [31:0] b_i,
  output logic [31:0] sum_o
);

  assign sum_o = a_i + b_i;

endmodule
