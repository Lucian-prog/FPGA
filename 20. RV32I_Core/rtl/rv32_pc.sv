// =============================================================================
// rv32_pc —— 程序计数器（Program Counter）
// -----------------------------------------------------------------------------
// 教学要点：
//   PC 是整个处理器最核心的“体系结构状态”（architectural state）。
//   它回答一个问题：本周期从指令存储器的哪个地址取指令？
//
//   在单周期处理器里，状态元件只有三类：PC、寄存器堆、数据存储器。
//   其余一切（译码、ALU、MUX）都是组合逻辑，它们的任务是在一个时钟
//   周期内算出“下一个 PC”和“下一个寄存器值”，然后在时钟沿提交。
//
//   本模块就是一个 32 位寄存器：
//     - 复位时 PC 归零，程序从地址 0 开始执行；
//     - 每个时钟上升沿把 pc_next_i（PC+4 或跳转目标）采样进来。
//
//   注意这里用的是“低有效异步复位”：rst_n_i 拉低的瞬间 pc_o 立刻归零，
//   不等时钟沿。这与寄存器堆、数据存储器的“同步写”形成对照——
//   复位是少数允许异步行为的信号，因为它不属于正常数据流。
// =============================================================================
module rv32_pc (
  input  logic        clk_i,      // 系统时钟
  input  logic        rst_n_i,    // 低有效异步复位
  input  logic [31:0] pc_next_i,  // 下一周期要执行的指令地址（PC+4 或跳转目标）
  output logic [31:0] pc_o        // 当前指令地址，直接送往指令存储器
);

  // PC 是处理器的体系结构状态，只在复位或时钟上升沿发生改变。
  // 这就是“单周期”的含义：每条指令恰好占用一个时钟周期，
  // 周期结束时 PC 前进一步，同时本条指令的所有写操作一并提交。
  always_ff @(posedge clk_i or negedge rst_n_i) begin
    if (!rst_n_i) begin
      pc_o <= 32'h0000_0000;      // 复位向量：本教学核固定从 0 地址启动
    end else begin
      pc_o <= pc_next_i;          // 提交下一 PC，进入下一条指令
    end
  end

endmodule
