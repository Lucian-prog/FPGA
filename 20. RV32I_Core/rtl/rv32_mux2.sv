// =============================================================================
// rv32_mux2 —— 二选一多路选择器（参数化位宽）
// -----------------------------------------------------------------------------
// 教学要点：
//   MUX 是单周期数据通路的“交通警察”：控制器通过 select 信号决定
//   本周期哪条数据流可以通行。本核心里有两处使用二选一 MUX：
//     1. PC 选择    —— select = pc_src：0 取 PC+4（顺序），1 取 PC+imm（跳转）；
//     2. ALU 源选择 —— select = alu_src：0 取 rs2（R-type），1 取立即数（I-type）。
//
//   参数化 WIDTH 让同一个模块可以用于任意位宽，这是可复用设计的基本功。
//
//   硬件本质：WIDTH 个并联的 2 选 1 选择器（每位一个），纯组合逻辑。
// =============================================================================
module rv32_mux2 #(
  parameter int WIDTH = 32    // 数据位宽，默认 32 位
) (
  input  logic [WIDTH-1:0] data0_i,   // select = 0 时输出这一路
  input  logic [WIDTH-1:0] data1_i,   // select = 1 时输出这一路
  input  logic             select_i,  // 选择信号，来自控制器
  output logic [WIDTH-1:0] data_o
);

  assign data_o = select_i ? data1_i : data0_i;

endmodule
