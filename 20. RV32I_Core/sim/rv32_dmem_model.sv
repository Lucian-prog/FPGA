// =============================================================================
// rv32_dmem_model —— 数据存储器仿真模型（组合读 + 同步写 RAM）
// -----------------------------------------------------------------------------
// 教学要点：
//   这是 rv32_core 时序契约的另一半：数据存储器。
//   契约内容（README “存储器时序契约”一节）：
//     组合读：地址变化 → 同一周期内读数据变化。
//             这让 lw 能在一个周期内完成“ALU 算地址 → 读存储器 →
//             经写回 MUX → 寄存器堆写口”的完整路径。
//     同步写：write_en_i=1 时，下一个时钟上升沿才把数据落入阵列。
//             与寄存器堆的写端口同理，保证本周期内读到的还是旧值。
//
//   与寄存器堆对比着看很有意思：两者都是“组合读 + 同步写”的小阵列，
//   区别只在数据存储器只有一个读写共用地址口，且没有 x0 这种特殊项。
//
//   简化假设（教学核明确不做的部分）：
//     - 只支持 4 字节对齐的整字 lw/sw，没有字节写使能；
//     - 不做非对齐检测，越界地址的高位被静默截断（数组下标回绕）；
//     - 没有访问异常——这些在真实处理器里都属于 trap/异常机制，
//       而教学核刻意不包含异常电路。
// =============================================================================
module rv32_dmem_model #(
  parameter int DEPTH = 64    // 存储深度（字数），默认 64×32bit = 256 字节
) (
  input  logic        clk_i,      // 时钟（写端口使用）
  input  logic        write_en_i, // 写使能（来自核心的 dmem_we_o）
  input  logic [31:0] addr_i,     // 访存地址（字节地址，ALU 计算结果）
  input  logic [31:0] wdata_i,    // 写数据（rs2 寄存器内容）
  output logic [31:0] rdata_o     // 读数据（送往核心的写回 MUX）
);

  localparam int INDEX_WIDTH = $clog2(DEPTH);  // 数组下标所需位数

  logic [31:0] mem [0:DEPTH-1];   // 存储阵列
  integer i;

  // 数据存储器上电清零：让 lw 读到确定的 0 而不是 X，
  // 仿真波形更干净，错误也更容易定位。
  initial begin
    for (i = 0; i < DEPTH; i = i + 1) begin
      mem[i] = 32'h0000_0000;
    end
  end

  // 组合读使 lw 能在一个时钟周期内完成地址计算、读出和写回。
  // 同样把字节地址右移 2 位转换成字下标。
  assign rdata_o = mem[addr_i[INDEX_WIDTH+1:2]];

  // sw 在上升沿提交写入；本模型只支持对齐的 32 位整字写。
  // 注意读和写用同一个下标表达式：sw 写的同时 rdata_o 仍是旧值，
  // 因为非阻塞赋值在沿之后才更新阵列。
  always_ff @(posedge clk_i) begin
    if (write_en_i) begin
      mem[addr_i[INDEX_WIDTH+1:2]] <= wdata_i;
    end
  end

endmodule
